-- Controlled dictionary of adverse event terms. The structure accepts MedDRA
-- codes (meddra_code) so a licensed MedDRA release can be loaded later.
CREATE TABLE IF NOT EXISTS pv.event_terms (
    term_id BIGINT GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
    preferred_term VARCHAR(255) NOT NULL UNIQUE,
    system_organ_class VARCHAR(255) NOT NULL,
    meddra_code VARCHAR(20),
    is_active BOOLEAN NOT NULL DEFAULT TRUE,
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);

-- Alternative wordings that map to a preferred term. Stored lower-case with
-- single spaces and no punctuation, matching the coding normaliser.
CREATE TABLE IF NOT EXISTS pv.event_term_synonyms (
    synonym_id BIGINT GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
    synonym VARCHAR(255) NOT NULL UNIQUE,
    term_id BIGINT NOT NULL
        REFERENCES pv.event_terms(term_id) ON DELETE CASCADE,
    added_by BIGINT REFERENCES pv.users(user_id) ON DELETE SET NULL,
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);

-- One row per reported (verbatim) event term in a case.
CREATE TABLE IF NOT EXISTS pv.case_event_terms (
    case_event_term_id BIGINT GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
    case_id BIGINT NOT NULL
        REFERENCES pv.safety_cases(case_id) ON DELETE CASCADE,
    verbatim_term VARCHAR(500) NOT NULL,
    term_id BIGINT REFERENCES pv.event_terms(term_id) ON DELETE SET NULL,
    coding_method VARCHAR(30) NOT NULL CHECK (
        coding_method IN ('Exact', 'Synonym', 'Suggested', 'Manual', 'Uncoded')
    ),
    coded_by BIGINT REFERENCES pv.users(user_id) ON DELETE SET NULL,
    coded_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    UNIQUE (case_id, verbatim_term)
);

CREATE INDEX IF NOT EXISTS idx_case_event_terms_term
    ON pv.case_event_terms(term_id);

